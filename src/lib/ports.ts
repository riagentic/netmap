export const httpScheme = (port: number): "http" | "https" | null =>
  HTTPS.has(port) ? "https" : HTTP.has(port) ? "http" : null;

export const serviceName = (port: number, etc: Map<number, string>): string =>
  KNOWN[port] ?? etc.get(port) ?? "";
